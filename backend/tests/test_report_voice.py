def test_the_preparer_is_named_when_given(df):
    text = _pdf_text(df, prepared_by="S. Mishra, Data Analytics")
    assert "S. Mishra, Data Analytics" in text
    assert "responsible for the analysis" in text


def test_no_preparer_line_when_none_is_given(df):
    text = _pdf_text(df)
    assert "responsible for the analysis" not in text


def test_the_client_is_named_in_the_basis_of_preparation(df):
    text = _pdf_text(df)
    assert "Prepared for Acme" in text


def test_the_health_report_carries_the_agency_name(df):
    text = _health_text(df, agency="Shweta Analytics")
    assert "Shweta Analytics" in text


def test_a_preparer_name_with_an_ampersand_does_not_break_the_pdf(df):
    """ReportLab reads the text as mini-HTML; "Shah & Co" would otherwise
    truncate the paragraph at the ampersand."""
    text = _pdf_text(df, prepared_by="Shah & Co Analytics")
    assert "Shah & Co Analytics" in text
