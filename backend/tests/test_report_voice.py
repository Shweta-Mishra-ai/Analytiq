def test_the_methodology_states_the_tests_used(df):
    text = _pdf_text(df)
    for expected in ("Shapiro", "Spearman", "Mann-Whitney", "IQR",
                     "Chi-square"):
        assert expected in text, expected


def test_the_methodology_records_judgement_not_just_procedure(df):
    """A list of tests is a feature list. What makes it read as an
    analyst's account is saying what was chosen over what, and why."""
    text = _pdf_text(df)
    assert "Judgement applied" in text
    assert "more conservative was taken" in text


def test_the_methodology_states_what_the_analysis_will_not_claim(df):
    text = _pdf_text(df).lower()
    assert "do not establish causation" in text
    assert "rather than answering it from general expectation" in text


def test_the_methodology_explains_withheld_findings(df):
    """Silence about what was dropped invites the assumption that
    nothing was."""
    text = _pdf_text(df)
    assert "withheld" in text


